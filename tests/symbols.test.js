import {eq} from './assert.js';
import {parseSymbol, yahooUrl, parseYahoo, frankfurterUrl, parseFrankfurter, formatPrice, formatChange, ageText} from '../lib/logic/symbols.js';

eq(parseSymbol(' usd/inr '), {kind: 'fx', base: 'USD', quote: 'INR', label: 'USD/INR', key: 'USD_INR'}, 'fx');
eq(parseSymbol('^NSEI').label, 'NIFTY 50', 'index label');
eq(parseSymbol('^BSESN').label, 'SENSEX', 'sensex label');
eq(parseSymbol('^NSEI').key, '_NSEI', 'filesystem-safe key');
eq(parseSymbol('AAPL'), {kind: 'stock', symbol: 'AAPL', label: 'AAPL', key: 'AAPL'}, 'stock');
eq(parseSymbol('reliance.ns').symbol, 'RELIANCE.NS', 'stock upper-cased');
eq(parseSymbol(''), null, 'empty');
eq(parseSymbol('   '), null, 'blank');
eq(parseSymbol('../../etc/passwd').key, '______ETC_PASSWD', 'key cannot escape the cache dir');
eq(yahooUrl('^NSEI'), 'https://query1.finance.yahoo.com/v8/finance/chart/%5ENSEI?range=1d&interval=1d', 'encoded');
eq(frankfurterUrl('USD', 'INR', new Date(2026, 10, 16)), 'https://api.frankfurter.dev/v1/2026-11-09..?base=USD&symbols=INR', 'series from a week ago');
eq(parseYahoo({chart: {result: [{meta: {regularMarketPrice: 110, chartPreviousClose: 100}}]}}), {price: 110, changePct: 10}, 'yahoo');
const fx = parseFrankfurter({rates: {'2026-11-13': {INR: 84.5}, '2026-11-12': {INR: 84}}}, 'INR');
eq(fx.price, 84.5, 'latest by date, not key order');
eq(Math.round(fx.changePct * 1000), 595, 'change vs previous day');
// Review Focus 3
eq(parseYahoo({chart: {result: null, error: {code: 'Not Found'}}}), null, 'unknown symbol');
eq(parseYahoo({}), null, 'empty body');
eq(parseYahoo(null), null, 'null body');
eq(parseYahoo({chart: {result: [{meta: {regularMarketPrice: 110}}]}}), null, 'missing previous close');
eq(parseYahoo({chart: {result: [{meta: {regularMarketPrice: 'x', chartPreviousClose: 100}}]}}), null, 'non-numeric price');
eq(parseYahoo({chart: {result: [{meta: {regularMarketPrice: 110, chartPreviousClose: 0}}]}}), null, 'zero previous close');
eq(parseFrankfurter({rates: {'2026-11-13': {INR: 84.5}}}, 'INR'), null, 'only one day');
eq(parseFrankfurter({rates: {}}, 'INR'), null, 'no rates');
eq(parseFrankfurter({}, 'INR'), null, 'no rates key');
eq(parseFrankfurter({rates: {'2026-11-13': {EUR: 1}, '2026-11-12': {EUR: 1}}}, 'INR'), null, 'currency missing');
eq(formatPrice(24812.4, 'en-US'), '24,812', 'big');
eq(formatPrice(84.4189, 'en-US'), '84.42', 'small');
eq(formatChange(0.44), '▲0.4%', 'up');
eq(formatChange(-0.06), '▼0.1%', 'down');
eq(formatChange(0), '0.0%', 'flat');
eq(formatChange(-0.01), '0.0%', 'rounds to flat without a stray arrow');
eq(ageText(0), 'just now', 'age now');
eq(ageText(5 * 60 * 1000), '5m ago', 'age minutes');
eq(ageText(2 * 3600 * 1000 + 5), '2h ago', 'age hours');
eq(ageText(3 * 86400 * 1000), '3d ago', 'age days');
